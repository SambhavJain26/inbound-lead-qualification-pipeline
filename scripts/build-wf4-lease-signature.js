/**
 * Builds n8n-workflows/wf4-lease-and-signature.json.
 *
 * WF4 populates the lease from verified data, sends it for signature through the
 * DocuSign developer sandbox, and closes the loop when it comes back signed.
 *
 * The lease is a fixed template with variable slots. The model never writes a
 * clause and never sees this workflow.
 *
 * Run: node scripts/build-wf4-lease-signature.js
 */

const path = require("path");
const wf = require("./lib/wf-common");
const { REPO_ROOT } = require("./lib/env");

const OUT = path.join(REPO_ROOT, "n8n-workflows", "wf4-lease-and-signature.json");

/**
 * Lease body. Sent to DocuSign as HTML, which it converts to PDF - far simpler
 * than generating a PDF here, and the anchor text below is what DocuSign uses to
 * place the signature tab.
 */
const buildLeaseCode = [
  "// Fixed template, variable slots. Nothing here is model-generated.",
  "const app = $('Load Application For Lease').first().json;",
  "",
  "function money(value) {",
  "  return '$' + Number(value || 0).toLocaleString('en-US', { minimumFractionDigits: 2 });",
  "}",
  "",
  "const conditional = app.decision === 'conditional';",
  "",
  "const rows = [",
  "  ['Resident', app.full_name],",
  "  ['Premises', app.address],",
  "  ['Unit', app.unit_code],",
  "  ['Lease term', app.lease_term_months + ' months'],",
  "  ['Monthly rent', money(app.rent_amount)],",
  "  ['Security deposit', money(app.deposit_amount)],",
  "  ['Intended move-in', app.desired_move_in || 'to be confirmed'],",
  "  ['Application reference', app.ref_token],",
  "];",
  "",
  "const rowsHtml = rows.map(function (r) {",
  "  return '<tr><td class=\"k\">' + r[0] + '</td><td class=\"v\">' + r[1] + '</td></tr>';",
  "}).join('');",
  "",
  "const conditionalBlock = conditional",
  "  ? '<p class=\"note\"><strong>Conditional approval.</strong> This offer was approved with " +
  "conditions. Any additional deposit or guarantor requirement will be confirmed by the " +
  "property manager before this lease takes effect.</p>'",
  "  : '';",
  "",
  "const html = [",
  "  '<html><head><meta charset=\"utf-8\"><style>',",
  "  'body{font-family:Helvetica,Arial,sans-serif;font-size:12pt;color:#111;margin:48px;}',",
  "  'h1{font-size:18pt;margin-bottom:4px;} h2{font-size:12pt;margin-top:28px;}',",
  "  'table{border-collapse:collapse;margin-top:16px;width:100%;}',",
  "  'td{padding:7px 10px;border-bottom:1px solid #ddd;} .k{color:#555;width:220px;}',",
  "  '.v{font-weight:600;} .note{background:#f4f4f4;padding:12px;margin-top:20px;}',",
  "  '.sig{margin-top:52px;} .demo{margin-top:40px;color:#777;font-size:9pt;}',",
  "  '</style></head><body>',",
  "  '<h1>Residential Lease Agreement</h1>',",
  "  '<div>' + app.address + '</div>',",
  "  '<table>' + rowsHtml + '</table>',",
  "  conditionalBlock,",
  "  '<h2>Agreement</h2>',",
  "  '<p>The resident named above agrees to lease the premises described above for the term ',",
  "  'and rent stated, subject to the property rules provided separately. This document is ',",
  "  'generated for a demonstration and is not a binding agreement.</p>',",
  "  '<div class=\"sig\"><p>Resident signature:</p><p>/sig1/</p>',",
  "  '<p>Date: /date1/</p></div>',",
  "  '<p class=\"demo\">Generated by the leasing demo on ' + new Date().toISOString().slice(0, 10) +",
  "  '. Synthetic data only.</p>',",
  "  '</body></html>',",
  "].join('');",
  "",
  "return [{ json: {",
  "  ref_token: app.ref_token,",
  "  full_name: app.full_name,",
  "  email: app.email,",
  "  unit_code: app.unit_code,",
  "  address: app.address,",
  "  rent_amount: app.rent_amount,",
  "  decision: app.decision,",
  "  document_base64: Buffer.from(html, 'utf8').toString('base64'),",
  "} }];",
].join("\n");

const parseConnectCode = [
  "// DocuSign Connect callback. The envelope is configured to post here when it",
  "// completes, so no Connect setup is needed in the DocuSign admin UI.",
  "const out = [];",
  "for (const item of $input.all()) {",
  "  const body = item.json.body || item.json;",
  "  const data = body.data || {};",
  "  const envelopeId = data.envelopeId || body.envelopeId || null;",
  "  const status = String(body.event || data.envelopeSummary && data.envelopeSummary.status || '')",
  "    .toLowerCase();",
  "",
  "  out.push({ json: {",
  "    envelope_id: envelopeId,",
  "    raw_event: body.event || null,",
  "    is_completed: status.indexOf('completed') !== -1,",
  "  } });",
  "}",
  "return out;",
].join("\n");

const envelopeGuardCode = [
  "// Did the UPDATE actually match an application?",
  "//",
  "// alwaysOutputData means a miss arrives here as an empty item rather than",
  "// stopping the branch, and strict IF nodes need a real boolean - not",
  "// truthiness on a missing field.",
  "const rows = $input.all().filter((item) => item.json && item.json.ref_token);",
  "if (!rows.length) {",
  "  const parsed = $('Parse Connect Event').first().json;",
  "  return [{ json: { application_found: false, envelope_id: parsed.envelope_id || null } }];",
  "}",
  "return [{ json: Object.assign({}, rows[0].json, { application_found: true }) }];",
].join("\n");

/* ------------------------------------------------------------------ nodes */

const nodes = [
  wf.webhookNode("Lease Requested", "lease-create", [-720, 0]),

  wf.postgresNode(
    "Load Application For Lease",
    "SELECT a.*, u.unit_code, u.address, u.rent_amount, u.deposit_amount, u.lease_term_months\n" +
      "FROM applications a JOIN units u ON u.id = a.unit_id\n" +
      "WHERE a.ref_token = $1 AND a.envelope_id IS NULL\n" +
      "LIMIT 1;",
    [-500, 0],
    {
      // envelope_id IS NULL in the WHERE clause is the second half of the
      // double-tap guard: even if this workflow is called twice, the second call
      // finds no row and sends nothing.
      queryOptions: { queryReplacement: "={{ [$json.body.ref_token] }}" },
    }
  ),

  wf.codeNode("Build Lease Document", buildLeaseCode, [-280, 0]),

  {
    id: "sign-docusign-jwt",
    name: "Sign DocuSign JWT",
    type: "n8n-nodes-base.jwt",
    typeVersion: 1,
    position: [-60, 0],
    parameters: {
      operation: "sign",
      useJson: true,
      claimsJson:
        "={{ JSON.stringify({" +
        " iss: '__DOCUSIGN_INTEGRATION_KEY__'," +
        " sub: '__DOCUSIGN_USER_ID__'," +
        " aud: 'account-d.docusign.com'," +
        " iat: Math.floor(Date.now()/1000)," +
        " exp: Math.floor(Date.now()/1000) + 3600," +
        " scope: 'signature impersonation'" +
        "}) }}",
      options: { algorithm: "RS256" },
    },
    credentials: { jwtAuth: { id: wf.PLACEHOLDER.DOCUSIGN, name: "Leasing DocuSign JWT signing key" } },
  },

  {
    id: "exchange-docusign-token",
    name: "Exchange JWT For Token",
    type: "n8n-nodes-base.httpRequest",
    typeVersion: 4.2,
    position: [160, 0],
    parameters: {
      method: "POST",
      url: "__DOCUSIGN_AUTH_BASE__/oauth/token",
      sendBody: true,
      contentType: "form-urlencoded",
      bodyParameters: {
        parameters: [
          { name: "grant_type", value: "urn:ietf:params:oauth:grant-type:jwt-bearer" },
          { name: "assertion", value: "={{ $json.token }}" },
        ],
      },
      options: { timeout: 30000 },
    },
  },

  {
    id: "create-docusign-envelope",
    name: "Create Lease Envelope",
    type: "n8n-nodes-base.httpRequest",
    typeVersion: 4.2,
    position: [380, 0],
    parameters: {
      method: "POST",
      url: "__DOCUSIGN_BASE_PATH__/v2.1/accounts/__DOCUSIGN_ACCOUNT_ID__/envelopes",
      sendHeaders: true,
      headerParameters: {
        parameters: [{ name: "Authorization", value: "=Bearer {{ $json.access_token }}" }],
      },
      sendBody: true,
      contentType: "json",
      specifyBody: "json",
      jsonBody:
        "={{ JSON.stringify({\n" +
        "  emailSubject: 'Your lease for ' + $('Build Lease Document').first().json.address,\n" +
        "  status: 'sent',\n" +
        "  documents: [{\n" +
        "    documentBase64: $('Build Lease Document').first().json.document_base64,\n" +
        "    name: 'Residential Lease Agreement',\n" +
        "    fileExtension: 'html',\n" +
        "    documentId: '1'\n" +
        "  }],\n" +
        "  recipients: { signers: [{\n" +
        "    email: $('Build Lease Document').first().json.email,\n" +
        "    name: $('Build Lease Document').first().json.full_name,\n" +
        "    recipientId: '1',\n" +
        "    routingOrder: '1',\n" +
        "    tabs: {\n" +
        "      signHereTabs: [{ anchorString: '/sig1/', anchorUnits: 'pixels', anchorXOffset: '0', anchorYOffset: '0' }],\n" +
        "      dateSignedTabs: [{ anchorString: '/date1/', anchorUnits: 'pixels', anchorXOffset: '0', anchorYOffset: '0' }]\n" +
        "    }\n" +
        "  }] },\n" +
        // Per-envelope Connect configuration, so nothing has to be set up in the
        // DocuSign admin UI. `events` requires deliveryMode SIM and eventData
        // together - omit either and DocuSign rejects the whole envelope.
        "  eventNotification: {\n" +
        "    url: '__TUNNEL_URL__webhook/docusign-status',\n" +
        "    loggingEnabled: 'true',\n" +
        "    requireAcknowledgment: 'true',\n" +
        "    includeDocuments: 'false',\n" +
        "    deliveryMode: 'SIM',\n" +
        "    eventData: { version: 'restv2.1' },\n" +
        "    events: ['envelope-completed']\n" +
        "  }\n" +
        "}) }}",
      options: { timeout: 60000 },
    },
  },

  wf.postgresNode(
    "Record Envelope Sent",
    "UPDATE applications SET\n" +
      "  envelope_id = $2,\n" +
      "  lease_status = 'sent',\n" +
      "  lease_sent_at = now(),\n" +
      "  status = 'lease_sent'\n" +
      "WHERE ref_token = $1 RETURNING *;",
    [600, 0],
    {
      queryOptions: {
        queryReplacement:
          "={{ [$('Build Lease Document').first().json.ref_token, $json.envelopeId] }}",
      },
    }
  ),

  wf.telegramNode(
    "Notify Manager: Lease Sent",
    {
      chatId: "=__TELEGRAM_CHAT_ID__",
      text:
        "=Lease sent for {{ $('Build Lease Document').first().json.ref_token }} - " +
        "{{ $('Build Lease Document').first().json.full_name }}.\n\n" +
        "{{ $('Build Lease Document').first().json.unit_code }}, " +
        "signature requested from {{ $('Build Lease Document').first().json.email }}.",
    },
    [820, 0]
  ),

  /* ---- signature returned ---------------------------------------------- */
  // Responds immediately. A human signing takes minutes; holding the HTTP
  // response open for that would time out and DocuSign would retry.
  wf.webhookNode("Signature Returned (DocuSign)", "docusign-status", [-720, 280]),

  wf.codeNode("Parse Connect Event", parseConnectCode, [-500, 280]),

  wf.ifNode(
    "Envelope Completed?",
    [wf.booleanCondition("={{ $json.is_completed }}", true)],
    [-280, 280]
  ),

  wf.postgresNode(
    "Mark Lease Signed",
    "UPDATE applications SET\n" +
      "  lease_status = 'signed',\n" +
      "  lease_signed_at = now(),\n" +
      "  status = 'lease_signed'\n" +
      "WHERE envelope_id = $1\n" +
      "RETURNING *, (SELECT unit_code FROM units WHERE id = applications.unit_id) AS unit_code,\n" +
      "          (SELECT address FROM units WHERE id = applications.unit_id) AS address;",
    [-60, 220],
    {
      queryOptions: { queryReplacement: "={{ [$json.envelope_id] }}" },
      alwaysOutputData: true,
    }
  ),

  wf.codeNode("Application Found For Envelope?", envelopeGuardCode, [60, 220]),

  wf.ifNode(
    "Signature Matches An Application?",
    [wf.booleanCondition("={{ $json.application_found }}", true)],
    [160, 220]
  ),

  // A completion callback for an envelope with no application behind it stops
  // and tells a human. Without this the run continues on an empty item and
  // dies at the mail node with "No recipients defined", which says nothing
  // about the actual problem.
  wf.telegramNode(
    "Alert Manager: Unknown Envelope",
    {
      chatId: "=__TELEGRAM_CHAT_ID__",
      text:
        "=A signed envelope came back that does not match any application.\n\n" +
        "Envelope: {{ $json.envelope_id }}\n\n" +
        "Nothing was recorded and no welcome packet was sent. This usually means " +
        "the demo state was reset after the lease went out.",
    },
    [260, 340]
  ),

  wf.postgresNode(
    "Mark Unit Leased",
    "UPDATE units SET status = 'leased' WHERE id = $1 RETURNING *;",
    [160, 220],
    { queryOptions: { queryReplacement: "={{ [$json.unit_id] }}" } }
  ),

  wf.emailSendNode(
    "Send Welcome Packet",
    {
      fromEmail: "=__SYSTEM_EMAIL__",
      toEmail: "={{ $('Mark Lease Signed').first().json.email }}",
      subject:
        "=Welcome to {{ $('Mark Lease Signed').first().json.address }} " +
        "[{{ $('Mark Lease Signed').first().json.ref_token }}]",
      text:
        "=Hi {{ $('Mark Lease Signed').first().json.full_name }},\n\n" +
        "Your lease is signed and {{ $('Mark Lease Signed').first().json.unit_code }} is yours.\n\n" +
        "Before move-in we will send over renters insurance details, utility setup, and your " +
        "permanent entry code. If anything needs sorting before then, just reply to this email.\n\n" +
        "Welcome aboard.\n\nThe leasing team",
    },
    [380, 220]
  ),

  wf.postgresNode(
    "Log Welcome Packet",
    "INSERT INTO message_log\n" +
      "  (ref_token, direction, channel, tier, from_addr, to_addr, subject, body, message_id)\n" +
      "VALUES ($1, 'outbound', 'email', 'A', '__SYSTEM_EMAIL__', $2, $3, $4, $5)\n" +
      "ON CONFLICT (message_id) DO NOTHING;",
    [600, 320],
    {
      queryOptions: {
        queryReplacement:
          "={{ [" +
          "$('Mark Lease Signed').first().json.ref_token, " +
          "($('Mark Lease Signed').first().json.email ?? ''), " +
          "'Welcome to ' + $('Mark Lease Signed').first().json.address, " +
          "'Welcome packet: insurance, utilities and the permanent entry code', " +
          "'mail-welcome-' + $('Mark Lease Signed').first().json.ref_token" +
          "] }}",
      },
      // Logging must never take down a send that already succeeded.
      continueOnFail: true,
    }
  ),

  wf.telegramNode(
    "Notify Manager: Lease Signed",
    {
      chatId: "=__TELEGRAM_CHAT_ID__",
      text:
        "=Signed. {{ $('Mark Lease Signed').first().json.ref_token }} - " +
        "{{ $('Mark Lease Signed').first().json.full_name }}.\n\n" +
        "{{ $('Mark Lease Signed').first().json.unit_code }} is now marked leased and the " +
        "welcome packet has gone out.",
    },
    [600, 220]
  ),
];

const connections = wf.connect({
  "Lease Requested": [["Load Application For Lease"]],
  "Load Application For Lease": [["Build Lease Document"]],
  "Build Lease Document": [["Sign DocuSign JWT"]],
  "Sign DocuSign JWT": [["Exchange JWT For Token"]],
  "Exchange JWT For Token": [["Create Lease Envelope"]],
  "Create Lease Envelope": [["Record Envelope Sent"]],
  "Record Envelope Sent": [["Notify Manager: Lease Sent"]],

  "Signature Returned (DocuSign)": [["Parse Connect Event"]],
  "Parse Connect Event": [["Envelope Completed?"]],
  "Envelope Completed?": [["Mark Lease Signed"], []],
  "Mark Lease Signed": [["Application Found For Envelope?"]],
  "Application Found For Envelope?": [["Signature Matches An Application?"]],
  "Signature Matches An Application?": [["Mark Unit Leased"], ["Alert Manager: Unknown Envelope"]],
  "Mark Unit Leased": [["Send Welcome Packet"]],
  "Send Welcome Packet": [["Log Welcome Packet", "Notify Manager: Lease Signed"]],
});

const workflow = wf.buildWorkflow({
  id: "wf4-lease-and-signature",
  name: "WF4 Lease And Signature",
  nodes,
  connections,
  active: true,
});

console.log(`wf4-lease-and-signature.json written, ${wf.writeWorkflow(workflow, OUT)} nodes`);
